"""v8.0 (owner): find the people in every room panorama so Evee can stand at the same size as the nearest one.
Writes scripts/room_people.gd: for each room, the floor people [x, top, h, feet_seen] (fractions of the panorama's
width / height) and a perspective fit h = a * feet + b from the people whose feet show.
Needs OpenCV 4.x with darknet (a venv: pip install --only-binary=:all: opencv-python-headless==4.10.0.84 numpy)
and the YOLOv4-tiny weights (downloaded on first run).
usage: <venv>/bin/python tools/rooms/evee_people.py [assets/rooms]"""
import os, sys, glob, json, urllib.request
import cv2, numpy as np
D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '.yolo')
os.makedirs(D, exist_ok=True)
for name, url in [('yolov4-tiny.weights', 'https://github.com/AlexeyAB/darknet/releases/download/darknet_yolo_v4_pre/yolov4-tiny.weights'),
                  ('yolov4-tiny.cfg', 'https://raw.githubusercontent.com/AlexeyAB/darknet/master/cfg/yolov4-tiny.cfg')]:
    if not os.path.exists(os.path.join(D, name)): urllib.request.urlretrieve(url, os.path.join(D, name))
net = cv2.dnn.readNetFromDarknet(os.path.join(D, 'yolov4-tiny.cfg'), os.path.join(D, 'yolov4-tiny.weights'))
ln = [net.getLayerNames()[i - 1] for i in net.getUnconnectedOutLayers().flatten()]

def people(path, thr=0.3):
    im = cv2.imread(path); H, W = im.shape[:2]
    out = []
    for x0 in range(0, W, H // 2):
        tile = im[:, x0:x0 + H] if x0 + H <= W else np.concatenate([im[:, x0:], im[:, :x0 + H - W]], axis=1)
        net.setInput(cv2.dnn.blobFromImage(tile, 1 / 255.0, (608, 608), swapRB=True, crop=False))
        for o in net.forward(ln):
            for d in o:
                sc = d[5:]; c = int(np.argmax(sc)); conf = float(sc[c]) * float(d[4])
                if c == 0 and conf > thr:
                    cx, cy, w, h = d[0] * H, d[1] * H, d[2] * H, d[3] * H
                    out.append([(x0 + cx - w / 2) % W, max(0.0, cy - h / 2), w, min(h, H - max(0.0, cy - h / 2)), conf])
    keep = cv2.dnn.NMSBoxes([b[:4] for b in out], [b[4] for b in out], thr, 0.4)
    return W, H, [out[i] for i in np.array(keep).flatten()] if len(keep) else []

def fit(rows):
    # floor people whose feet show: h = a * feet + b (all in fractions of the panorama height); RANSAC over pairs
    pts = [(r[1] + r[2], r[2]) for r in rows if r[3] and r[1] + r[2] > 0.5]
    if len(pts) < 3: return [1.0 / 0.55, -0.45 / 0.55]   # (no fit: a horizon at 45 %, a person's feet 55 % below it)
    best, bi = None, -1
    rng = np.random.default_rng(1)
    for _ in range(300):
        i, j = rng.choice(len(pts), 2, replace=False)
        (f1, h1), (f2, h2) = pts[i], pts[j]
        if abs(f2 - f1) < 0.03: continue
        a = (h2 - h1) / (f2 - f1); b = h1 - a * f1
        if not (0.3 < a < 6.0): continue
        n = sum(1 for f, h in pts if abs(a * f + b - h) < 0.06)
        if n > bi: best, bi = (a, b), n
    if best is None: return [1.0 / 0.55, -0.45 / 0.55]
    a, b = best
    inl = np.array([(f, h) for f, h in pts if abs(a * f + b - h) < 0.06])
    if len(inl) >= 3: a, b = np.polyfit(inl[:, 0], inl[:, 1], 1)
    return [round(float(a), 4), round(float(b), 4)]

root = sys.argv[1] if len(sys.argv) > 1 else 'assets/rooms'
data = {}
for path in sorted(glob.glob(os.path.join(root, '*', '*.jpg'))):
    f = os.path.basename(os.path.dirname(path)); rn = os.path.splitext(os.path.basename(path))[0]
    W, H, ps = people(path)
    rows = []
    for x, y, w, h, c in ps:
        top, hh = y / H, h / H
        if top + hh < 0.5 or hh < 0.18: continue   # (only people standing on the main floor, not the balconies)
        rows.append([round(float((x + w / 2) / W), 4), round(float(top), 4), round(float(hh), 4), 1 if y + h < H * 0.975 else 0])
    data['%s_%s' % (f, rn)] = {'people': rows, 'fit': fit(rows)}
    print('%s_%s: %d floor people, fit %s' % (f, rn, len(rows), data['%s_%s' % (f, rn)]['fit']))
with open('scripts/room_people.gd', 'w') as o:
    o.write('## v8.0 (generated by tools/rooms/evee_people.py): the people standing on each room\'s floor, so Evee can\n')
    o.write('## match the nearest one. [x, top, h, feet_seen] as fractions of the panorama; fit: h = a * feet + b.\n')
    o.write('extends RefCounted\n\nconst ROOMS := ' + json.dumps(data, separators=(',', ':')) + '\n')
